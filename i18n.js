// Saved preference wins; otherwise fr* browser language; otherwise English.
var detectUiLang = function(saved, browserLang) {
    if (saved === 'fr' || saved === 'en') {
        return saved;
    }
    if (browserLang && browserLang.toLowerCase().indexOf('fr') === 0) {
        return 'fr';
    }
    return 'en';
};
